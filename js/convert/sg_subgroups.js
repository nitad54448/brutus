/* The maximal subgroups of a space group, from its operators (International Tables A1, as used by Bilbao's SUBGROUPGRAPH):
 *
 *   t  translationengleiche  the lattice is kept, the point group shrinks (Fm-3m > I4/mmm, index 3)
 *   k  klassengleiche        the point group is kept, the lattice shrinks to a sublattice of index 2, 3 or 4
 *                            (Fm-3m > Pm-3m, index 4): the cell of the subgroup is larger
 *
 *   Subgroups.enumerate(ops) -> [{kind, index, B, nrep, reps, ops}]
 *     ops   every operator of the setting [{r: [9], t: [3]}] (the centring translations included)
 *     B     the basis of the lattice of the subgroup, in the old axes (row-major, its COLUMNS are the basis vectors)
 *     reps  the operators of the subgroup modulo its lattice, in the old axes
 *     ops   the same in the axes of B, with t in [0, 1): what a symmetry engine needs, with two atoms, to name the group
 *   Subgroups.probe(cand, cell) -> {cell, atoms, ops}: the cell of B and two atoms at general positions
 *   Subgroups.compose(cand, P, p) -> {P, p}: the engine's standardising transformation of that cell, in the old axes
 *
 * The conversion of a phase to a subgroup is SGConvert's (sg_convert.js); this file only finds the subgroups.
 *
 *    page    :  <script defer src="js/sg_subgroups.js">
 *    node    :  require('./sg_subgroups.js')
 */
(function (root) {
  'use strict';
  var I3 = [1, 0, 0, 0, 1, 0, 0, 0, 1], D = 24, TOL = 1e-6;
  function mul3(a, b) { var o = new Array(9); for (var i = 0; i < 3; i++) for (var j = 0; j < 3; j++) o[i * 3 + j] = a[i * 3] * b[j] + a[i * 3 + 1] * b[3 + j] + a[i * 3 + 2] * b[6 + j]; return o; }
  function mulv(m, v) { return [m[0] * v[0] + m[1] * v[1] + m[2] * v[2], m[3] * v[0] + m[4] * v[1] + m[5] * v[2], m[6] * v[0] + m[7] * v[1] + m[8] * v[2]]; }
  function det3(m) { return m[0] * (m[4] * m[8] - m[5] * m[7]) - m[1] * (m[3] * m[8] - m[5] * m[6]) + m[2] * (m[3] * m[7] - m[4] * m[6]); }
  function inv3(m) {
    var d = det3(m);
    return [(m[4] * m[8] - m[5] * m[7]) / d, (m[2] * m[7] - m[1] * m[8]) / d, (m[1] * m[5] - m[2] * m[4]) / d, (m[5] * m[6] - m[3] * m[8]) / d, (m[0] * m[8] - m[2] * m[6]) / d, (m[2] * m[3] - m[0] * m[5]) / d, (m[3] * m[7] - m[4] * m[6]) / d, (m[1] * m[6] - m[0] * m[7]) / d, (m[0] * m[4] - m[1] * m[3]) / d];
  }
  function isInt(v) { return Math.abs(v - Math.round(v)) < TOL; }
  function allInt(a) { return a.every(isInt); }
  function frac(v) { v -= Math.floor(v + TOL); return Math.abs(v) < TOL ? 0 : v; }
  function rotKey(r) { return r.map(Math.round).join(','); }
  // the product a after b
  function compose(a, b) { var t = mulv(a.r, b.t); return { r: mul3(a.r, b.r).map(Math.round), t: [t[0] + a.t[0], t[1] + a.t[1], t[2] + a.t[2]] }; }
  // the class of a translation in the lattice with basis columns B (inverse Bi): its fractional coordinates, as a key
  function classKey(Bi, t) { return mulv(Bi, t).map(function (v) { return Math.round(frac(v) * 1e4); }).join(','); }

  /* The lattice generated by the integer translations and the centring translations: a basis of three vectors (rows of the
     result are the vectors, in the old axes). Integer row reduction on vectors scaled by D. */
  function latticeBasis(ops) {
    var rows = [[D, 0, 0], [0, D, 0], [0, 0, D]];
    ops.forEach(function (o) { if (rotKey(o.r) === rotKey(I3)) rows.push(o.t.map(function (v) { return Math.round(frac(v) * D); })); });
    var basis = [];
    for (var col = 0; col < 3; col++) {
      for (;;) {
        var nz = rows.filter(function (r) { return r[col] !== 0; });
        if (nz.length <= 1) break;
        nz.sort(function (a, b) { return Math.abs(a[col]) - Math.abs(b[col]); });
        for (var i = 1; i < nz.length; i++) { var q = Math.trunc(nz[i][col] / nz[0][col]); for (var k = 0; k < 3; k++) nz[i][k] -= q * nz[0][k]; }
      }
      var piv = rows.filter(function (r) { return r[col] !== 0; })[0];
      basis.push(piv); rows = rows.filter(function (r) { return r !== piv; });
    }
    return basis;
  }
  function columns(rows) { var B = new Array(9); for (var j = 0; j < 3; j++) for (var i = 0; i < 3; i++) B[i * 3 + j] = rows[j][i] / D; return B; }

  // the subgroups of a finite group given by its multiplication table (indices), as sorted index arrays: joins of cyclic ones
  function subgroupsOf(n, mul) {
    function closure(set) {
      var inSet = {}, list = [];
      set.forEach(function (i) { if (!inSet[i]) { inSet[i] = true; list.push(i); } });
      for (var changed = true; changed;) {
        changed = false;
        for (var a = 0; a < list.length; a++) for (var b = 0; b < list.length; b++) { var c = mul[list[a]][list[b]]; if (!inSet[c]) { inSet[c] = true; list.push(c); changed = true; } }
      }
      return list.sort(function (x, y) { return x - y; });
    }
    var seen = {}, all = [];
    function add(list) { var k = list.join(','); if (seen[k]) return false; seen[k] = true; all.push(list); return true; }
    for (var g = 0; g < n; g++) add(closure([0, g]));
    for (var more = true; more;) {
      more = false;
      var cur = all.slice();
      for (var i = 0; i < cur.length; i++) for (var j = i + 1; j < cur.length; j++) if (add(closure(cur[i].concat(cur[j])))) more = true;
    }
    return { all: all, closure: closure };
  }

  // the sublattices of index n of a lattice, as integer matrices H (upper triangular, row-major): the new basis is B H
  function sublattices(n) {
    var out = [];
    for (var d1 = 1; d1 <= n; d1++) if (n % d1 === 0) for (var d2 = 1; d2 <= n / d1; d2++) if ((n / d1) % d2 === 0) {
      var d3 = n / d1 / d2;
      for (var a = 0; a < d1; a++) for (var b = 0; b < d1; b++) for (var c = 0; c < d2; c++) out.push([d1, a, b, 0, d2, c, 0, 0, d3]);
    }
    return out;
  }

  function enumerate(ops) {
    var L = latticeBasis(ops), B = columns(L), Bi = inv3(B);
    // one operator per rotation modulo the lattice: G / L is the point group
    var reps = [], byRot = {};
    ops.forEach(function (o) { var k = rotKey(o.r); if (!byRot[k]) { byRot[k] = true; reps.push({ r: o.r.map(Math.round), t: o.t.slice() }); } });
    reps.sort(function (a, b) { return (rotKey(a.r) === rotKey(I3) ? 0 : 1) - (rotKey(b.r) === rotKey(I3) ? 0 : 1); });
    var n = reps.length, index = {};
    reps.forEach(function (o, i) { index[rotKey(o.r)] = i; });
    var mul = reps.map(function (a) { return reps.map(function (b) { return index[rotKey(mul3(a.r, b.r))]; }); });
    if (n < 2) return [];
    var cands = [];
    // t: every maximal proper subgroup of the point group, with the whole lattice
    var lat = subgroupsOf(n, mul), subs = lat.all.filter(function (s) { return s.length < n; });
    subs.filter(function (s) { return !subs.some(function (u) { return u.length > s.length && s.every(function (i) { return u.indexOf(i) >= 0; }); }); }).forEach(function (s) {
      cands.push({ kind: 't', index: n / s.length, B: B, reps: s.map(function (i) { return reps[i]; }) });
    });
    // k: sublattices of index 2, 3, 4 that the point group keeps, with a section of the group over them
    var gens = (function () { var g = [], cur = [0]; for (var i = 1; i < n && cur.length < n; i++) if (cur.indexOf(i) < 0) { g.push(i); cur = lat.closure(cur.concat([i])); } return g; })();
    [2, 3, 4].forEach(function (m) {
      sublattices(m).forEach(function (H) {
        var B2 = mul3(B, H), B2i = inv3(B2), Hi = inv3(H);
        if (!reps.every(function (o) { return allInt(mul3(Hi, mul3(mul3(Bi, mul3(o.r, B)), H))); })) return;
        // the cosets of the new lattice in the old one: m of them, from the lattice points B (i j k) of a box
        var shifts = [], seenShift = {};
        for (var i = 0; i < m; i++) for (var j = 0; j < m; j++) for (var k = 0; k < m; k++) {
          var t = mulv(B, [i, j, k]), key = classKey(B2i, t);
          if (!seenShift[key]) { seenShift[key] = true; shifts.push(t); }
        }
        var found = {};
        (function choose(g, picked) {
          if (g === gens.length) {
            var elems = {}, list = [];
            function put(o) { var key = rotKey(o.r) + '|' + classKey(B2i, o.t); if (elems[key]) return false; elems[key] = true; list.push(o); return true; }
            put({ r: I3.slice(), t: [0, 0, 0] });
            picked.forEach(put);
            for (var changed = true; changed && list.length <= n;) {
              changed = false;
              for (var a = 0; a < list.length && list.length <= n; a++) for (var b = 0; b < list.length && list.length <= n; b++) if (put(compose(list[a], list[b]))) changed = true;
            }
            if (list.length !== n) return;
            var id = list.map(function (o) { return rotKey(o.r) + '|' + classKey(B2i, o.t); }).sort().join(';');
            if (found[id]) return;
            found[id] = true;
            cands.push({ kind: 'k', index: m, B: B2, reps: list });
            return;
          }
          shifts.forEach(function (s) { var o = reps[gens[g]]; choose(g + 1, picked.concat([{ r: o.r, t: [o.t[0] + s[0], o.t[1] + s[1], o.t[2] + s[2]] }])); });
        })(0, []);
      });
    });
    // index of each candidate in the whole group, its operators in the axes of its own lattice, then only the maximal ones
    cands.forEach(function (c) {
      c.nrep = c.reps.length;
      c.index = Math.round((n / c.nrep) * Math.abs(det3(c.B) / det3(B)));
      var Ci = inv3(c.B);
      c.ops = c.reps.map(function (o) { return { r: mul3(Ci, mul3(o.r, c.B)).map(Math.round), t: mulv(Ci, o.t).map(frac) }; });
    });
    function contained(s, u) {
      if (!allInt(mul3(inv3(u.B), s.B))) return false;
      var Ui = inv3(u.B);
      return s.reps.every(function (o) { return u.reps.some(function (h) { return rotKey(h.r) === rotKey(o.r) && allInt(mulv(Ui, [o.t[0] - h.t[0], o.t[1] - h.t[1], o.t[2] - h.t[2]])); }); });
    }
    cands = cands.filter(function (s) { return !cands.some(function (u) { return u !== s && u.index < s.index && contained(s, u); }); });
    cands.sort(function (a, b) { return a.index - b.index || (a.kind < b.kind ? -1 : a.kind > b.kind ? 1 : 0); });
    return cands;
  }

  function metric(c) {
    var r = Math.PI / 180, ca = Math.cos(c.alpha * r), cb = Math.cos(c.beta * r), cg = Math.cos(c.gamma * r);
    return [c.a * c.a, c.a * c.b * cg, c.a * c.c * cb, c.a * c.b * cg, c.b * c.b, c.b * c.c * ca, c.a * c.c * cb, c.b * c.c * ca, c.c * c.c];
  }
  function cellFromMetric(G) {
    var a = Math.sqrt(G[0]), b = Math.sqrt(G[4]), c = Math.sqrt(G[8]), d = 180 / Math.PI, acos = function (x) { return Math.acos(Math.max(-1, Math.min(1, x))) * d; };
    return { a: a, b: b, c: c, alpha: acos(G[5] / (b * c)), beta: acos(G[2] / (a * c)), gamma: acos(G[1] / (a * b)) };
  }
  // the cell of the subgroup lattice, and two atoms of different kinds at general positions under the subgroup operators (one alone has the hidden inversion of a polar group): the engine names the group
  function probe(cand, cell) {
    var Bt = [cand.B[0], cand.B[3], cand.B[6], cand.B[1], cand.B[4], cand.B[7], cand.B[2], cand.B[5], cand.B[8]];
    return { cell: cellFromMetric(mul3(mul3(Bt, metric(cell)), cand.B)), atoms: [{ label: 'X', type: 'X', x: 0.1157, y: 0.2761, z: 0.3913, occ: 1 }, { label: 'Y', type: 'Y', x: 0.6372, y: 0.0846, z: 0.7219, occ: 1 }], ops: cand.ops };
  }
  // the engine's P, p (relative to the cell of probe) in the axes of the group the candidate is a subgroup of
  // the engine works to a tolerance: its P and p are rationals with small denominators, written with a little noise
  function snap(v) { var r = Math.round(v * D) / D; return Math.abs(v - r) < 0.02 ? r + 0 : v; }
  function composeTransform(cand, P, p) { return { P: mul3(cand.B, P.map(snap)).map(snap), p: mulv(cand.B, p.map(snap)).map(snap) }; }

  var api = { enumerate: enumerate, probe: probe, compose: composeTransform, TOLERANCES: [0.001, 0.005, 0.01, 0.02, 0.05] };
  root.Subgroups = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof globalThis !== 'undefined' ? globalThis : this);
